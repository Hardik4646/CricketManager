export function createPlayer({
  id,
  name,
  jersey,
  age,
  role,
  battingStyle,
  bowlingType, // 'pace' | 'spin' | 'none'
  bowlingStyle,
  isUserPlayer = false,
  isRival = false,
  isCaptain = false,
  isWicketkeeper = false,
  teamColor = '#3B82F6',
  batting = {},
  bowling = {},
  fielding = {},
  mental = {},
}) {
  return {
    id,
    name,
    jersey,
    age,
    role,
    battingStyle,
    bowlingType,
    bowlingStyle,
    isUserPlayer,
    isRival,
    isCaptain,
    isWicketkeeper,
    // [NANOBANA.NET / NANAIMG.IO]: Replace with consistent character portrait URI
    portraitUri: getPlayerPortraitUri(name, teamColor, jersey),
    batting: {
      technique: batting.technique ?? 65,
      power: batting.power ?? 65,
      timing: batting.timing ?? 65,
      consistency: batting.consistency ?? 65,
      aggression: batting.aggression ?? 65,
      vsSpin: batting.vsSpin ?? 65,
      vsPace: batting.vsPace ?? 65,
      pressureHandling: batting.pressureHandling ?? 65,
      runningBetweenWickets: batting.runningBetweenWickets ?? 70,
    },
    bowling: {
      primarySkill: bowling.primarySkill ?? 30,
      accuracy: bowling.accuracy ?? 30,
      variation: bowling.variation ?? 25,
      movement: bowling.movement ?? 25,
      deathBowling: bowling.deathBowling ?? 25,
      powerplayBowling: bowling.powerplayBowling ?? 25,
      wicketTaking: bowling.wicketTaking ?? 25,
      economyControl: bowling.economyControl ?? 30,
      fitnessStamina: bowling.fitnessStamina ?? 75,
    },
    fielding: {
      catching: fielding?.catching ?? 72,
      groundFielding: fielding?.groundFielding ?? 74,
      throwing: fielding?.throwing ?? 70,
      athleticism: fielding?.athleticism ?? 75,
      keeping: isWicketkeeper ? (fielding?.keeping ?? 84) : 20,
    },
    mental: {
      bigMatchTemperament: mental?.bigMatchTemperament ?? 70,
      leadership: mental?.leadership ?? 60,
      fitnessLevel: mental?.fitnessLevel ?? 82,
      recoveryRate: mental?.recoveryRate ?? 78,
      form: mental?.form ?? 74,
      confidence: mental?.confidence ?? 75,
    },
  };
}

